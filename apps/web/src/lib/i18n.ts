/* ------------------------------------------------- French typography */

const NBSP = ' ';
const NNBSP = ' ';

function frenchTypography(s: string): string {
  return s
    .replace(/ :/g, `${NBSP}:`)
    .replace(/ ([;?!])/g, `${NNBSP}$1`)
    .replace(/« /g, `«${NBSP}`)
    .replace(/ »/g, `${NBSP}»`)
    .replace(/(\d) %/g, `$1${NBSP}%`)
    .replace(/(\d) \$/g, `$1${NBSP}$`)
    .replace(/(\d) h\b/g, `$1${NBSP}h`)
    .replace(/(\d) min\b/g, `$1${NBSP}min`)
    .replace(/(\d) kWh/g, `$1${NBSP}kWh`);
}

function typo<T>(value: T): T {
  if (typeof value === 'string') return frenchTypography(value) as T;
  if (typeof value === 'function') {
    const fn = value as (...args: unknown[]) => unknown;
    return ((...args: unknown[]) => typo(fn(...args))) as T;
  }
  if (Array.isArray(value)) return value.map(typo) as T;
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value)) out[k] = typo(v);
    return out as T;
  }
  return value;
}

